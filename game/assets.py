    col, a = _sphere((30, 135, 250), (C, C), (BASE_R, BASE_R))
    cv.over(col, a)
    rng = np.random.RandomState(1)
    L = cv.layer()
    for _ in range(190):
        ang, rad = rng.uniform(0, 2 * math.pi), BASE_R * math.sqrt(rng.uniform(0, 0.92))

def _load_png(path):
    img = cv2.imread(path, cv2.IMREAD_UNCHANGED)
    if img is None or img.ndim != 3 or img.shape[2] != 4:
        print(f"[assets] skipping {os.path.basename(path)} (needs a PNG with transparency)")
        return None
    if img.shape[:2] == (PAD, PAD):                   # our own pre-centred sprites: use as-is
        return img
    ys, xs = np.where(img[..., 3] > 10)
    if len(xs) == 0:
        return None
    img = img[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
    h, w = img.shape[:2]
    s = (2 * BASE_R * 1.05) / max(h, w)
    img = cv2.resize(img, (max(1, int(w * s)), max(1, int(h * s))), interpolation=cv2.INTER_AREA)
    h, w = img.shape[:2]
    canvas = np.zeros((PAD, PAD, 4), np.uint8)
    y0, x0 = (PAD - h) // 2, (PAD - w) // 2
    canvas[y0:y0 + h, x0:x0 + w] = img
    return canvas


def _avg_colour(img):
    m = img[..., 3] > 200
    return tuple(int(v) for v in img[..., :3][m].mean(axis=0)) if m.any() else (120, 200, 230)


@dataclass
class FruitSprite:
    name: str
    img: np.ndarray
    flesh: tuple
    juice: tuple
    band: float
    radius: float
    bomb: bool = False
    cut_img: Optional[np.ndarray] = None     # cross-section shown on the halves (None -> flesh-band fallback)


class SpriteSet:
    def __init__(self, asset_dir=ASSET_DIR):
        cut_dir = os.path.join(os.path.dirname(asset_dir), "cut")
        files = {os.path.splitext(os.path.basename(p))[0].lower(): p
                 for p in sorted(glob.glob(os.path.join(asset_dir, "*.png")))}
        self.fruits = {}
        for name, build in BUILDERS.items():          # built-ins missing on disk are drawn procedurally
            if name not in files:
                self.fruits[name] = FruitSprite(name, build(), radius=BASE_R * 0.95,
                                                cut_img=INTERIORS[name](), **META[name])
        self.bomb = FruitSprite("bomb", _bomb(), (40, 40, 60), (40, 150, 255), 6, BASE_R * 0.9, True)
        loaded = 0
        for name, path in files.items():
            img = _load_png(path)
            if img is None:
                continue
            if name == "bomb":
                self.bomb.img = img
                continue
            cut_path = os.path.join(cut_dir, name + ".png")
            cut = _load_png(cut_path) if os.path.exists(cut_path) else None
            meta = dict(META.get(name) or {})
            if not meta:
                avg = np.array(_avg_colour(img), np.float32)
                meta = dict(flesh=tuple(int(v) for v in avg * 0.5 + 127), juice=tuple(int(v) for v in avg), band=10)
            self.fruits[name] = FruitSprite(name, img, radius=BASE_R * 0.95, cut_img=cut, **meta)
            loaded += 1
        print(f"[assets] {len(self.fruits)} fruits ready ({loaded} loaded from {asset_dir})")

    def choose(self, rng):
        return rng.choice(list(self.fruits.values()))



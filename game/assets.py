"""Fruit sprites.

Everything is stored as PNG files in ``assets/`` (generated by ``tools/make_assets.py``):

    assets/fruits/<name>.png   whole fruit, 240x240 transparent
    assets/cut/<name>.png      the INSIDE of that fruit (cross-section) - shown on the two halves
    assets/fruits/bomb.png     the bomb
    assets/sounds/*.wav        sound effects

You can replace any of them with your own transparent PNGs. If a fruit has no matching
``assets/cut/<name>.png`` the game falls back to cutting the whole image and painting a
flesh-coloured edge. If a PNG is missing entirely, a procedurally drawn sprite is used.
"""
import glob
import math
import os
from dataclasses import dataclass
from typing import Optional

import cv2
import numpy as np

PAD = 240          # side of the square sprite canvas
BASE_R = 70        # fruit radius in px at 720p (scaled with window height)
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSET_DIR = os.path.join(ROOT, "assets", "fruits")

_YY, _XX = (a.astype(np.float32) for a in np.mgrid[0:PAD, 0:PAD])
C = PAD / 2.0


def _P(x, y):
    return int(round(x)), int(round(y))


# --------------------------------------------------------------------------
# compositing helpers
# --------------------------------------------------------------------------
class _Canvas:
    def __init__(self):
        self.c = np.zeros((PAD, PAD, 3), np.float32)
        self.a = np.zeros((PAD, PAD), np.float32)

    def over(self, col, alpha):
        alpha = np.clip(alpha, 0.0, 1.0)
        out_a = alpha + self.a * (1.0 - alpha)
        w = (alpha / np.maximum(out_a, 1e-6))[..., None]
        self.c = col * w + self.c * (1.0 - w)
        self.a = out_a

    @staticmethod
    def layer():
        return np.zeros((PAD, PAD, 4), np.uint8)

    def over_layer(self, layer, opacity=1.0):
        # cv2 anti-aliasing on a transparent layer darkens edges; undo that.
        a = layer[..., 3].astype(np.float32) / 255.0
        col = np.clip(layer[..., :3].astype(np.float32) / np.maximum(a, 1e-3)[..., None], 0, 255)
        self.over(col, a * opacity)

    def image(self):
        return np.dstack([np.clip(self.c, 0, 255), self.a * 255.0]).astype(np.uint8)


def _sphere(base, centre, axes, spec=0.55, ambient=0.40, norm=None):
    """Lit ellipsoid -> (bgr float32 HxWx3, alpha float32 HxW)."""
    if norm is None:
        nx = (_XX - centre[0]) / axes[0]
        ny = (_YY - centre[1]) / axes[1]
    else:
        nx, ny = norm
    r2 = nx * nx + ny * ny
    nz = np.sqrt(np.clip(1.0 - r2, 0.0, 1.0))
    light = np.array([-0.45, -0.55, 0.70], np.float32)
    light /= np.linalg.norm(light)
    diff = np.clip(nx * light[0] + ny * light[1] + nz * light[2], 0.0, 1.0)
    base_arr = np.asarray(base, np.float32)
    if base_arr.ndim == 1:
        base_arr = base_arr.reshape(1, 1, 3)
    col = base_arr * (ambient + (1.0 - ambient) * diff[..., None] * 1.18)
    col = col * (0.72 + 0.28 * nz)[..., None]
    col = col + ((diff ** 30) * spec * 255.0)[..., None]
    alpha = np.clip((1.0 - np.sqrt(r2)) * min(axes) / 1.5, 0.0, 1.0)
    return np.clip(col, 0, 255), alpha


def _rotate(img, deg):
    M = cv2.getRotationMatrix2D((PAD / 2, PAD / 2), deg, 1.0)
    return cv2.warpAffine(img, M, (PAD, PAD), flags=cv2.INTER_LINEAR,
                          borderMode=cv2.BORDER_CONSTANT, borderValue=(0, 0, 0, 0))


# ---- helpers for the cut faces ------------------------------------------------
def _polar(axes, centre):
    nx = (_XX - centre[0]) / axes[0]
    ny = (_YY - centre[1]) / axes[1]
    return np.sqrt(nx * nx + ny * ny), np.arctan2(ny, nx)


def _band(r, a, b, soft=0.02):
    """1 where a < r < b (soft edges), shape HxWx1."""
    return (np.clip((r - a) / soft, 0, 1) * np.clip((b - r) / soft, 0, 1))[..., None]


def _paint(col, m, colour):
    return col * (1.0 - m) + np.asarray(colour, np.float32) * m


def _noise(seed, sigma=1.5):
    n = cv2.GaussianBlur(np.random.RandomState(seed).rand(PAD, PAD).astype(np.float32), (0, 0), sigma)
    return (n - n.mean()) / (n.std() + 1e-6)


def _fill(colour):
    col = np.empty((PAD, PAD, 3), np.float32)
    col[:] = np.asarray(colour, np.float32)
    return col


def _face(col, r, axes):
    return np.dstack([np.clip(col, 0, 255), np.clip((1.0 - r) * min(axes) / 1.5, 0, 1) * 255.0]).astype(np.uint8)


def _u8(col):
    return np.clip(col, 0, 255).astype(np.uint8)



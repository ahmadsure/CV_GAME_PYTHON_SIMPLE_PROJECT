def _in_apple():
    ax, ctr = (BASE_R * 1.02, BASE_R * 0.95), (C, C + 5)
    r, th = _polar(ax, ctr)
    n = _noise(11, 2.0)
    col = _fill((205, 236, 246)) * (1.03 - 0.16 * r[..., None] ** 3 + 0.015 * n[..., None])
    col = _paint(col, _band(r, 0.84, 0.93, 0.05) * 0.5, (150, 200, 225))
    col = _paint(col, _band(r, 0.92, 1.2), (48, 48, 205))
    cx = ((_XX - ctr[0]) / (ax[0] * 0.24)) ** 2 + ((_YY - ctr[1]) / (ax[1] * 0.36)) ** 2
    col = _paint(col, np.clip((1 - cx) / 0.3, 0, 1)[..., None] * 0.9, (160, 210, 200))
    c8 = _u8(col)
    for s in (-1, 1):
        cv2.ellipse(c8, _P(ctr[0] + s * 8, ctr[1]), (5, 10), 0, 0, 360, (30, 60, 95), -1, cv2.LINE_AA)
    return _face(c8.astype(np.float32), r, ax)


def _wedge_face(ax, ctr, segs, flesh, pith, peel, seed, seeds=0, rot=0.0):
    r, th = _polar(ax, ctr)
    n = _noise(seed, 1.2)
    col = _fill(flesh) * (1.12 - 0.22 * r[..., None] + 0.05 * n[..., None])
    dist = r * (sum(ax) / 2) * np.abs(np.sin(segs / 2.0 * th)) / (segs / 2.0)
    sep = np.clip(1 - dist / 2.0, 0, 1)[..., None] * (r[..., None] < 0.85)
    col = _paint(col, sep, pith)
    col = _paint(col, _band(r, -1, 0.07, 0.04), pith)
    col = _paint(col, _band(r, 0.83, 0.91, 0.015), pith)
    col = _paint(col, _band(r, 0.90, 1.2), peel)
    c8 = _u8(col)
    rng = np.random.RandomState(seed)
    for _ in range(seeds):
        a, rad = rng.uniform(0, 2 * math.pi), rng.uniform(0.25, 0.65)
        cv2.ellipse(c8, _P(ctr[0] + math.cos(a) * rad * ax[0], ctr[1] + math.sin(a) * rad * ax[1]),
                    (6, 3), math.degrees(a), 0, 360, (170, 215, 225), -1, cv2.LINE_AA)
    img = _face(c8.astype(np.float32), r, ax)
    return _rotate(img, rot) if rot else img



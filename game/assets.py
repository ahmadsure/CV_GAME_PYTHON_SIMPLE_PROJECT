def blit_rgba(frame, sprite, cx, cy, angle=0.0, scale=1.0):
    """Alpha-blend a PAD x PAD BGRA sprite onto frame, rotated clockwise by angle degrees."""
    if angle or scale != 1.0:
        M = cv2.getRotationMatrix2D((PAD / 2, PAD / 2), -angle, scale)
        sprite = cv2.warpAffine(sprite, M, (PAD, PAD), flags=cv2.INTER_LINEAR,
                                borderMode=cv2.BORDER_CONSTANT, borderValue=(0, 0, 0, 0))
    x0, y0 = int(round(cx - PAD / 2)), int(round(cy - PAD / 2))
    fh, fw = frame.shape[:2]
    sx0, sy0 = max(0, -x0), max(0, -y0)
    sx1, sy1 = min(PAD, fw - x0), min(PAD, fh - y0)
    if sx1 <= sx0 or sy1 <= sy0:
        return
    roi = frame[y0 + sy0:y0 + sy1, x0 + sx0:x0 + sx1]
    s = sprite[sy0:sy1, sx0:sx1]
    a = s[..., 3:4].astype(np.float32) / 255.0
    roi[:] = (s[..., :3] * a + roi * (1.0 - a)).astype(np.uint8)


def cut_sprite(img, angle_deg, flesh=None, band=0.0):
    """Split a sprite along a line through its centre.

    Returns (half_a, half_b). half_a is the side the normal (-sin a, cos a) points to.
    With ``flesh`` given, a flesh-coloured edge of ``band`` px is painted on the cut (used when the
    sprite is a whole fruit); without it the sprite is assumed to already be the fruit's inside.
    """
    a = math.radians(angle_deg)
    d = -(_XX - C) * math.sin(a) + (_YY - C) * math.cos(a)   # signed distance to the cut line
    out = []
    for sign in (1.0, -1.0):
        dd = d * sign
        alpha = img[..., 3].astype(np.float32) * np.clip(dd + 0.5, 0.0, 1.0)
        col = img[..., :3].astype(np.float32)
        if flesh is not None:
            w = np.clip(1.0 - dd / max(band, 1e-3), 0.0, 1.0)[..., None]
            col = col * (1.0 - w) + np.asarray(flesh, np.float32) * w
        rim = (np.clip(1.0 - np.abs(dd - 1.5) / 1.5, 0.0, 1.0) * 0.4)[..., None]   # bright cut edge
        col = col + rim * (255.0 - col)
        half = np.empty_like(img)
        half[..., :3] = np.clip(col, 0, 255).astype(np.uint8)
        half[..., 3] = np.clip(alpha, 0, 255).astype(np.uint8)
        out.append(half)
    return out[0], out[1]
